const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({window:{},Intl,Map,Set,Number,Date,MT:require('./market-core.js')});
vm.runInContext(fs.readFileSync(__dirname+'/data.js','utf8'),ctx);
const app=fs.readFileSync(__dirname+'/app.js','utf8');
vm.runInContext(app.slice(0,app.indexOf('function apply(')),ctx);
vm.runInContext(app.slice(app.indexOf('function nearest('),app.indexOf('const changeHTML=')),ctx);
vm.runInContext('series=ingest(window.INITIAL).series;',ctx);
const ui=fs.readFileSync(__dirname+'/forecast-ui.js','utf8');
vm.runInContext(ui.slice(ui.indexOf('const fcState='),ui.indexOf('function fcWorkspace(')),ctx);
assert.equal(vm.runInContext('fcAll().length',ctx),7);
assert.equal(vm.runInContext('fcReference()',ctx),'1405/08/06');
vm.runInContext("const brent=fcAll().find(s=>s.name.includes('برنت'));const future=fcWindow(brent,fcReference(),12,false);",ctx);
assert.equal(vm.runInContext('future.length',ctx),4);
assert.equal(vm.runInContext('future[0].date',ctx),'1405/10/10');
assert.equal(vm.runInContext('future[0].value',ctx),101);
assert.ok(vm.runInContext('future.every(p=>p.date>fcReference()&&p.date<=shift(fcReference(),12))',ctx));
assert.equal(vm.runInContext('fcPrevious(brent,future[0]).date',ctx),'1405/07/08');
assert.equal(vm.runInContext('fcWindow(brent,fcReference(),0,false).length',ctx),21);
assert.equal(vm.runInContext('fcWindow(brent,fcReference(),0,true).length',ctx),25);
assert.equal(vm.runInContext("fcWindow(brent,'1411/01/01',12,false).length",ctx),0);
assert.equal(vm.runInContext('fcTrend(-0.1)',ctx),'↓ کمتر از ۱٪');
assert.equal(vm.runInContext('fcTrend(-25)',ctx),'↓ ۲۵٪');
assert.equal(vm.runInContext('fcTrend(0)',ctx),'بدون تغییر');
assert.equal(vm.runInContext('fcTrend(null)',ctx),'بدون مبنای مقایسه');
console.log('PASS: 7 source forecast series, nearest future horizon, bounded windows, archive isolation, real previous-horizon comparison and direction.');
