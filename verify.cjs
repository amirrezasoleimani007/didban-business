const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const core=require('./market-core.js');
const ctx=vm.createContext({window:{},Intl,Map,Set,Number,Date,console});
vm.runInContext(fs.readFileSync(__dirname+'/data.js','utf8'),ctx);
const source=fs.readFileSync(__dirname+'/app.js','utf8');
vm.runInContext(source.slice(0,source.indexOf('function apply(')),ctx);
vm.runInContext(source.slice(source.indexOf('function nearest('),source.indexOf('const changeHTML=')),ctx);
const result=vm.runInContext('ingest(window.INITIAL)',ctx);
const rate=result.series.find(s=>s.sheet==='Risk Free rate');
assert.ok(rate.points.length>900);
assert.equal(rate.points.at(-1).date,'1405/08/06');
assert.ok(Math.abs(rate.points.at(-1).value-42.0513)<1e-8);
assert.equal(result.series.find(s=>s.sheet==='Inflation').points.at(-1).value,73.6);
ctx.testRate=rate;
const metric=vm.runInContext('metric(testRate)',ctx);
assert.ok(Math.abs(metric.change-(metric.latest.value-metric.start.value))<1e-8);
assert.equal(core.toRialKg(470,'دلار بر تن',2735000),1285450);
assert.equal(core.toRialKg(94.8,'تومان بر کیلوگرم'),948);
assert.equal(core.toRialKg(470,'دلار بر تن',null),null);
assert.equal(core.toRialKg(1000,'ریال بر تن'),1);
assert.equal(core.percent(470,445),(470/445-1)*100);
assert.equal(core.percent(470,0),null);
assert.equal(core.gap(100,0),null);
assert.equal(core.family('گندله سنگ آهن'),'pellet');
const points=[{date:'1405/01/01',value:1},{date:'1405/01/04',value:2}];
assert.equal(core.nearest(points,'1405/01/03',2,s=>+s.slice(-2)).value,1);
assert.equal(core.nearest(points,'1405/01/03',1,s=>+s.slice(-2)),null);
assert.ok(core.csv([['=SUM(A1)','نام, محصول']]).includes("'=SUM(A1)"));
const unitTest={sheets:[{name:'Risk Free rate',rows:[['Date','Indicator','Unit','Value','تواتر'],['1405/08/06','نرخ','درصد',42,'روزانه']]}]};
ctx.unitTest=unitTest;
assert.equal(vm.runInContext('ingest(unitTest).series.length',ctx),0);
console.log(`PASS: ${result.series.length} series, ${rate.points.length} risk-free observations; scaling, percentage points, historic FX, missing data, date matching, CSV.`);
